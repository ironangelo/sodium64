RDP_BANK, MATH_BANK, PHASE_BANK = 0x190000, 0x1a0000, 0x180000


class ReturnVM(ShaderVM):
    def __init__(self, *args, stop_bank, **kwargs):
        super().__init__(*args, **kwargs)
        self.stop_bank = stop_bank

    def poll_dma(self):
        result = super().poll_dma()
        self.phase_loaded = bool(self.overlay_history and self.overlay_history[-1] == self.stop_bank)
        return result


def cpu_binding(cpu):
    image, syms = load_elf(cpu)
    text, data = (syms['rsp_hcomp_rdp_'+s+'_start'] for s in ('text', 'data'))
    assert data-text == 1000
    assert syms['rsp_hcomp_rdp_data_end']-data == 232
    original = image.copy()
    regs = [0]*32
    regs[8] = syms['rsp_hcomp_math_text_start'] | 5
    addr = parse_macros(ROOT).name
    cpu_execute(image, syms['hcomp_rdp_cpu_bind'], regs, {}, syms['hcomp_rdp_cpu_bind_end'])
    def read(a): return int.from_bytes(bytes(image[(a+i)&0x1fffffff] for i in range(4)), 'big')
    assert read(data) == syms['rsp_hcomp_math_text_start'] | 5
    assert read(0xa4000000+addr('OVERLAY_HCOMP_MATH_SRC')) == text | 5
    assert regs[9] & 0xe0000000 == 0xa0000000, 'descriptor publication must be uncached'
    allowed = set(range(data&0x1fffffff, (data&0x1fffffff)+4))
    dmem = (0xa4000000+addr('OVERLAY_HCOMP_MATH_SRC')) & 0x1fffffff
    allowed.update(range(dmem,dmem+4))
    assert all(image[k] == v for k,v in original.items() if k not in allowed)
    return dict(text_descriptor_distance=1000, uncached_publication=True)


def run_case(build, c, case_id):
    addr = parse_macros(ROOT).name
    main = build/'src/rsp_main.elf'
    rdp = build/'src/rsp_hcomp_rdp.elf'
    math = build/'src/rsp_hcomp_math.elf'
    phase = build/'src/rsp_hcomp.elf'
    _, maincode = read_text(main)
    _, rdpcode = read_text(rdp)
    _, mathcode = read_text(math)
    _, phasecode = read_text(phase)
    rdpdata = section(rdp,'.data')
    assert len(rdpcode) == len(mathcode) == len(phasecode) == 1000
    assert len(rdpdata) == 232
    # Independent literal generated by the official probe formula; host
    # command geometry below never uses the linked code's coordinate output.
    combiner = struct.unpack_from('>Q',rdpdata,8+48)[0]
    assert combiner >> 56 == 0x3c
    rows, y = c.get('rows',33), c.get('y',9)
    cgws, cad = c.get('cgws',0x82), c.get('cad',0x72)
    ts, fixed, wobj, limit = (c.get(k,v) for k,v in
                             (('ts',1),('fixed',0),('wobj',0),('limit',0)))
    admitted = (cgws&0x53 == 2 and bool(cad&0x40) and not wobj&0xa0 and
                not fixed&0xfffe and ts == 1 and not limit)
    queue = (case_id&1)*4
    framebuffer = 0xf2300
    pad = (y*16)&63
    sub, winner, presence = [addr(n)&0x1fffffff for n in
                            ('HCOMP_SUB_ORIGIN','HCOMP_WINNER_ORIGIN','HCOMP_PRESENCE_ORIGIN')]
    starts = [framebuffer+(y-8)*560+24] + [p+24-pad for p in (sub,winner,presence)]
    d = bytearray(section(main,'.data'))
    d[addr('TILE_TABLE'):addr('TILE_TABLE')+1024] = bytes([0x7d])*1024
    put(d,addr('OVERLAY_HCOMP_MATH_SRC'),RDP_BANK|5)
    put(d,addr('OVERLAY_HCOMP_SRC'),PHASE_BANK|3)
    put(d,addr('FRAMEBUFFER')+queue,framebuffer)
    put(d,addr('HCOMP_BAND_ROWS'),rows)
    put(d,addr('HCOMP_BAND_Y'),y)
    put(d,addr('HCOMP_DIAG_COMPOSE_LIMIT'),limit)
    for i,p in enumerate(starts[1:]): put(d,addr('HCOMP_BAND_BASES')+i*4,p)
    zbase = winner-(y*560+pad)
    put(d,addr('HCOMP_PROOF_RDP_CMDS')+20,zbase)
    d[addr('WOBJSEL')] = wobj
    d[addr('HCOMP_EFFECTIVE_TS')] = ts
    struct.pack_into('>H',d,addr('SUB_COLOR'),fixed)
    ram = bytearray([0xa5])*0x400000
    ram[RDP_BANK:RDP_BANK+1000] = rdpcode
    struct.pack_into('>II',ram,RDP_BANK+1000,MATH_BANK|5,0)
    ram[RDP_BANK+1008:RDP_BANK+1232] = rdpdata[8:]
    ram[MATH_BANK:MATH_BANK+1000] = mathcode
    ram[PHASE_BANK:PHASE_BANK+1000] = phasecode
    rng = random.Random(0x524450+case_id)
    expected = []
    for row in range(rows):
        row_expected = []
        for x in range(256):
            a,b = rng.randrange(32768),rng.randrange(32768)
            eligible = c.get('eligibility','mixed') == 'all' or (
                c.get('eligibility','mixed') == 'mixed' and (x+row)%3)
            exists = c.get('presence','mixed') == 'all' or (
                c.get('presence','mixed') == 'mixed' and (x+row)%5)
            values = (rgba(a),rgba(b),0xc00 if eligible else 0x400,0xc00 if exists else 0x400)
            for p,value in zip(starts,values): struct.pack_into('>H',ram,p+row*560+x*2,value)
            row_expected.append(reference(rgba(a)>>1,rgba(b)>>1,bool(cad&0x80),True)
                                if eligible and exists else rgba(a))
        expected.append(row_expected)
    before, dbefore = bytes(ram), bytes(d)
    owners = set(range(addr('TILE_TABLE'),addr('TILE_TABLE')+1024))
    owners.update(range(addr('SCRN_DATA'),addr('SCRN_DATA')+8))
    owners.update(range(addr('NATIVE_DIAG_RSP_BANK'),addr('NATIVE_DIAG_RSP_BANK')+2))
    ram_owner = {starts[2]+row*560+x for row in range(rows) for x in range(512)}
    regs = [0]*32
    regs[2],regs[3],regs[16],regs[26],regs[27],regs[29] = cgws,cad,starts[0],y-8,y-8+rows,queue
    code = bytearray(maincode)
    code[0x3a8:0x790] = rdpcode
    vm = ReturnVM(code,d,ram,regs,owners,ram_owner,case_id%7+2,
                  overlays={MATH_BANK:5,PHASE_BANK:3},stop_bank=3 if admitted else 5)
    vm.pc = 0x3b0
    steps = vm.execute(0x778 if admitted else 0x3b0,require_phase=True)
    assert vm.r[26:28] == regs[26:28]
    assert bytes(d[addr('VRAM_TABLE'):addr('SCRN_DATA')]) == dbefore[addr('VRAM_TABLE'):addr('SCRN_DATA')]
    assert all(ram[i] == b for i,b in enumerate(before) if i not in ram_owner)
    if not admitted:
        assert ram == before and not vm.captures
        assert vm.overlay_history == [5]
        assert vm.r[2:4] == [cgws,cad] and vm.r[16] == starts[0]
        assert d[addr('TILE_TABLE'):addr('TILE_TABLE')+1024] == dbefore[addr('TILE_TABLE'):addr('TILE_TABLE')+1024]
        return dict(admitted=False,steps=steps,policy=c)
    assert vm.overlay_history == [3]
    assert vm.v[20] == [0]*8
    tiles = vm.captures[:-4]
    assert len(tiles) == 8*((rows+31)//32)
    output = []
    for row in range(rows): output.append(list(struct.unpack_from('>256H',before,starts[0]+row*560)))
    seen = set()
    for tile_id,packet in enumerate(tiles):
        commands = struct.unpack('>28Q',packet)
        local_y,local_x = (tile_id//8)*32,(tile_id%8)*32
        height = min(32,rows-local_y)
        assert commands[0] == commands[-1] == 0x2700000000000000
        assert commands[1] == 0x2f100cf000000214
        assert commands[2]&0x1fffffff == framebuffer-4480
        assert commands[3] == 0x2d03000000430000 | (y*4<<32) | ((y+rows)*4)
        assert commands[4] == 0x3a000000ffffff80 and commands[5] == 0x3b000000fffffffb
        assert commands[6] == combiner | (0x28000 if cad&0x80 else 0)
        assert commands[7]&0x1fffffff == zbase
        assert commands[8] == 0x2e00000010000000
        for source,idx in ((0,9),(1,17)):
            assert commands[idx] == 0x2800000000000000
            assert commands[idx+1]&0x1fffffff == starts[source]
            tile_word = 0x3510100000000000 | (source*256<<32)
            assert commands[idx+2] == tile_word | 0x07080200
            assert commands[idx+3] == 0x2600000000000000
            assert commands[idx+4] == (0x3400000007000000 | (local_x*4<<44) |
                   (local_y*4<<32) | ((local_x+31)*4<<12) | ((local_y+height-1)*4))
            assert commands[idx+5] == 0x2700000000000000
            assert commands[idx+6] == tile_word | (source<<24) | 0x80200
            assert commands[idx+7] == 0x3200000000000000 | (source<<24) | (124<<12) | ((height-1)*4)
        x0,y0 = local_x+12,y+local_y
        assert commands[25] == (0x2400000000000000 | ((x0+32)*4<<44) |
                  ((y0+height)*4<<32) | (x0*4<<12) | (y0*4))
        assert commands[26] == 0x0000000004000400
        # Interpret the submitted coordinates and Z gate against independently
        # seeded original pixels, including absent Sub and forbidden Main.
        for ry in range(height):
            for rx in range(32):
                row,x = local_y+ry,local_x+rx
                assert (row,x) not in seen
                seen.add((row,x))
                z = struct.unpack_from('>H',ram,starts[2]+row*560+x*2)[0]
                assert z in (0x400,0xc00)
                if z == 0xc00:
                    a,b = [struct.unpack_from('>H',before,p+row*560+x*2)[0]>>1 for p in starts[:2]]
                    output[row][x] = reference(a,b,bool(cad&0x80),True)
    assert len(seen) == rows*256 and output == expected
    restore = [(addr('RDP_INIT'),addr('RDP_INIT')+64),
               (addr('RDP_FRAME')+8,addr('RDP_FILL')+8),
               (addr('RDP_FILL')+40,addr('RDP_FILL')+56),
               (addr('HCOMP_TEXTURE_FENCE'),addr('HCOMP_TEXTURE_FENCE')+8)]
    assert vm.captures[-4:] == [dbefore[start:end] for start,end in restore]
    expected_writes = 0 if c.get('presence','mixed') == 'all' else rows
    assert len([t for t in vm.transfers if t['write']]) == expected_writes
    return dict(admitted=True,steps=steps,tiles=len(tiles),pixels=len(seen),policy=c)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('build',type=Path)
    ap.add_argument('--cpu',type=Path,required=True)
    ap.add_argument('--baseline',type=Path,required=True)
    ap.add_argument('--output',type=Path)
    args = ap.parse_args()
    binding = cpu_binding(args.cpu)
    assert read_text(args.build/'src/rsp_hcomp_math.elf')[1] == read_text(args.baseline/'src/rsp_hcomp_math.elf')[1]
    cases = [dict(rows=r,y=8+(i%4),cad=m) for i,r in enumerate((1,31,32,33,224)) for m in (0x72,0xf2)]
    cases += [dict(cgws=w) for w in (2,0x22,0x82,0xa2)]
    cases += [dict(eligibility=e,presence=p) for e in ('all','none') for p in ('all','none')]
    cases += [dict(cgws=w) for w in (0,1,3,0x12,0x32,0x42,0xc2)]
    cases += [dict(wobj=w) for w in (0x20,0x80,0xa0)]
    cases += [dict(cad=0x32),dict(ts=0),dict(ts=2),dict(ts=0x11),dict(fixed=2),dict(limit=8)]
    result = [run_case(args.build,c,i) for i,c in enumerate(cases)]
    report = dict(passed=True,linked_cases=len(result),cpu_binding=binding,
                  pixels=sum(r.get('pixels',0) for r in result),original_math_byte_exact=True,
                  native_timing_authority=False,commercial_data=False,results=result,
                  candidate_sha256=hashlib.sha256(args.cpu.read_bytes()).hexdigest())
    if args.output: args.output.write_text(json.dumps(report,indent=2)+'\n')
    print('RDP_HALF_LINKED PASS',json.dumps({k:v for k,v in report.items() if k!='results'}))


if __name__ == '__main__': main()
